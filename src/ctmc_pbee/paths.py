"""Repository paths, independent of the current working directory.

Usage in a notebook or script::

    from ctmc_pbee.paths import DATA, output_dir

    with open(DATA / "SS-input-hazard-fragilities-20260512.pkl", "rb") as f:
        ...
    figdir = output_dir("case_study")      # creates output/case_study/ if needed
    plt.savefig(figdir / "my_figure.svg")

The repository root is located from this file's position (src/ctmc_pbee/paths.py),
which works for an editable install (``pip install -e .``). It can be overridden
with the environment variable ``CTMC_PBEE_ROOT``.
"""

import os
from pathlib import Path

ROOT = Path(os.environ.get("CTMC_PBEE_ROOT", Path(__file__).resolve().parents[2]))
DATA = ROOT / "data"          # input data (hazard, fragilities, recovery)
OUTPUT = ROOT / "output"      # figures and results regenerated by the notebooks
FIGURES = ROOT / "figures"    # benchmark figures (prefix B-) as published


def output_dir(name: str) -> Path:
    """Return ``output/<name>/``, creating it if it does not exist."""
    path = OUTPUT / name
    path.mkdir(parents=True, exist_ok=True)
    return path
