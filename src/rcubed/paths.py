"""Repository paths, independent of the current working directory.

Usage in a notebook or script::

    from rcubed.paths import DATA, output_dir

    with open(DATA / "SS-input-hazard-fragilities-20260512.pkl", "rb") as f:
        ...
    figdir = output_dir("case_study")      # creates output/case_study/ if needed
    plt.savefig(figdir / "my_figure.svg")

The repository root is located from this file's position (src/rcubed/paths.py),
which works for an editable install (``pip install -e .``). It can be overridden
with the environment variable ``RCUBED_ROOT``.
"""

import os
from pathlib import Path

ROOT = Path(os.environ.get("RCUBED_ROOT", Path(__file__).resolve().parents[2]))
DATA = ROOT / "data"          # input data (hazard, fragilities, recovery)
OUTPUT = ROOT / "output"      # figures and results regenerated by the notebooks
FIGURES = ROOT / "figures"    # benchmark figures (prefix B-) as published


# Case-study files that are confidential and not distributed with the repository
# (available upon request, see notebooks/02_case_study.ipynb).
CONFIDENTIAL_DATA = (
    "fixed-transition_params.json",
    "isolated-transition_params.json",
    "SS-input-hazard-fragilities-20260512.pkl",
)


class MissingDataError(FileNotFoundError):
    """Raised when an input file in data/ is missing (e.g. confidential case-study data)."""


def require_data(*names: str) -> None:
    """Check that the files ``data/<name>`` exist, otherwise raise a clear error.

    Use it at the top of a notebook or script, before loading the data::

        require_data("SS-input-hazard-fragilities-20260512.pkl")
    """
    missing = [n for n in names if not (DATA / n).is_file()]
    if not missing:
        return
    msg = [f"Missing input file(s) in {DATA}:"] + [f"  - {n}" for n in missing]
    if any(n in CONFIDENTIAL_DATA for n in missing):
        msg += [
            "",
            "The case-study data are confidential and are not included in the public",
            "repository. They are available upon request, for the reproduction of the",
            "figures only (Chiara Nardin, cnardin@ethz.ch). Once received, copy the files into",
            f"{DATA} with their original names and run this notebook again.",
            "The toy example (notebooks/01_toy_example.ipynb) runs without them.",
        ]
    raise MissingDataError("\n".join(msg))


def data_available(*names: str) -> bool:
    """True if all the files ``data/<name>`` exist."""
    return all((DATA / n).is_file() for n in names)


def output_dir(name: str) -> Path:
    """Return ``output/<name>/``, creating it if it does not exist."""
    path = OUTPUT / name
    path.mkdir(parents=True, exist_ok=True)
    return path
